-- =====================================================================
-- 2026-09-12 役員(greeting)に公開/非公開の切り替えを追加
--
-- 目的:
--   これまで greeting に登録した役員は登録と同時に必ずトップページの
--   「県連役員」「支部役員」タイルに表示されていた。is_published を
--   追加し、公開する人だけをトップに表示できるようにする。
--
-- 安全性:
--   何度実行しても同じ結果になる（冪等）。既定はtrueなので、既存の
--   表示内容は変化しない（今まで表示されていた人は表示されたまま）。
--
-- 適用方法:
--   Supabase ダッシュボード → SQL Editor に貼り付けて実行。
-- =====================================================================

alter table public.greeting add column if not exists is_published boolean not null default true;
